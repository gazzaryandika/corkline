// Probe the Sources flow (mock mode) and screenshot each step.
import fs from 'node:fs';
import { openApp, APP } from './lib.mjs';
const { browser, page } = await openApp();
await page.goto(APP);
await page.evaluate(() => localStorage.clear());
await page.reload();
await page.getByText('Blank board', { exact: true }).click();
await page.locator('input:focus').fill('Triodos Kids');
await page.locator('textarea').first().fill('As cash disappears, children aged 6–12 lose touch with money. How can a bank make it visible again?');
await page.getByRole('button', { name: 'Done' }).click();
await page.waitForTimeout(400);
await page.getByRole('button', { name: /Sources/ }).first().click();
await page.waitForTimeout(500);
await page.screenshot({ path: 'still-p1.png' });
const text = fs.readFileSync('assets/triodos-kids-brief.md', 'utf8');
const dt = await page.evaluateHandle((t) => { const d = new DataTransfer(); d.items.add(new File([t], 'triodos-kids-brief.md', { type: 'text/markdown' })); return d; }, text);
await page.dispatchEvent('.sources-drop', 'dragover', { dataTransfer: dt });
await page.dispatchEvent('.sources-drop', 'drop', { dataTransfer: dt });
await page.waitForTimeout(800);
await page.screenshot({ path: 'still-p2.png' });
await page.selectOption('select[aria-label="Document kind"]', 'context');
await page.getByRole('button', { name: 'Read with AI' }).click();
await page.waitForTimeout(1500);
await page.screenshot({ path: 'still-p3.png' });
await page.getByRole('button', { name: /Review \d+ card/ }).click();
await page.waitForTimeout(500);
await page.screenshot({ path: 'still-p4.png' });
await browser.close();
